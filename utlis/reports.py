from io import BytesIO
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    HRFlowable,
    Table,
    TableStyle
)
from datetime import datetime
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER


def generate_pdf_report(
    executive_summary,
    business_alerts,
    ai_insights,
    ai_recommendations,
    kpi_data=None
):

    buffer = BytesIO()

    doc = SimpleDocTemplate(buffer)
    from reportlab.lib import colors

    styles = getSampleStyleSheet()

    # ---------------- Title ---------------- #

    title_style = styles["Heading1"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.HexColor("#1F4E79")
    title_style.fontSize = 24
    title_style.spaceAfter = 15

    # ---------------- Section Heading ---------------- #

    heading = styles["Heading2"]
    heading.textColor = colors.HexColor("#2E75B6")
    heading.spaceBefore = 12
    heading.spaceAfter = 8

    # ---------------- Normal Text ---------------- #

    normal = styles["BodyText"]
    normal.leading = 18
    normal.spaceAfter = 4

    story = []

    # ---------------- Title ---------------- #
    story.append(Paragraph("AI BUSINESS INTELLIGENCE REPORT", title_style))

    story.append(
    Paragraph(
        "<b>Executive Business Report</b>",
        normal
    )
    )

    story.append(Spacer(1, 8))

    story.append(
    Paragraph(
        f"<b>Generated on:</b> {datetime.now().strftime('%d %B %Y | %I:%M %p')}",
        normal
    )
    )

    story.append(Spacer(1, 12))

    story.append(
    HRFlowable(
        width="100%",
        thickness=1.5,
        color=colors.HexColor("#1F4E79")
    )
    )

    story.append(Spacer(1, 15))
    # ---------------- KPI Summary ---------------- #

    if kpi_data:

        story.append(Paragraph("KPI SUMMARY", heading))
        story.append(Spacer(1, 8))

        table_data = [["KPI", "Value"]]

        for key, value in kpi_data.items():
            table_data.append([key, str(value)])

        table = Table(table_data, colWidths=[220, 120])

        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F4E79")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
            ("TOPPADDING", (0, 1), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 1), (-1, -1), 6),
    ]))

    story.append(table)
    story.append(Spacer(1, 20))

    # ---------------- Executive Summary ---------------- #

    story.append(Paragraph("Executive Summary", heading))
    story.append(Spacer(1, 6))

    for item in executive_summary:
        story.append(Paragraph(f"• {item}", normal))

    story.append(Spacer(1, 12))

    # ---------------- Business Alerts ---------------- #

    story.append(Paragraph("Business Alerts", heading))
    story.append(Spacer(1, 6))

    for item in business_alerts:
        story.append(Paragraph(f"• {item}", normal))

    story.append(Spacer(1, 12))

    # ---------------- AI Insights ---------------- #

    story.append(Paragraph("AI Business Insights", heading))
    story.append(Spacer(1, 6))

    for item in ai_insights:
        story.append(Paragraph(f"• {item}", normal))

    story.append(Spacer(1, 12))

    # ---------------- Recommendations ---------------- #

    story.append(Paragraph("AI Recommendations", heading))
    story.append(Spacer(1, 6))

    for item in ai_recommendations:
        story.append(Paragraph(f"• {item}", normal))

    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%"))
    story.append(Spacer(1, 10))

    story.append(
        Paragraph(
            "<b>Generated by AI Business Intelligence Assistant</b>",
            normal
        )
    )

    doc.build(story)

    pdf = buffer.getvalue()
    buffer.close()

    return pdf