from utlis.executive_summary import generate_executive_summary
from utlis.business_alerts import generate_business_alerts
from utlis.ai_insights import (
    generate_ai_insights,
    generate_ai_recommendations,
)


def generate_report(df):

    summary = generate_executive_summary(df)
    alerts = generate_business_alerts(df)
    insights = generate_ai_insights(df)
    recommendations = generate_ai_recommendations(df)

    report = ""

    report += "=" * 50 + "\n"
    report += "AI BUSINESS INTELLIGENCE REPORT\n"
    report += "=" * 50 + "\n\n"

    report += "EXECUTIVE SUMMARY\n"
    report += "-" * 50 + "\n"
    report += summary + "\n\n"

    report += "BUSINESS ALERTS\n"
    report += "-" * 50 + "\n"

    for alert in alerts:
        report += f"• {alert}\n"

    report += "\n"

    report += "AI INSIGHTS\n"
    report += "-" * 50 + "\n"

    for insight in insights:
        report += f"• {insight}\n"

    report += "\n"

    report += "AI RECOMMENDATIONS\n"
    report += "-" * 50 + "\n"

    for recommendation in recommendations:
        report += f"• {recommendation}\n"

    report += "\n"
    report += "=" * 50 + "\n"
    report += "Generated by AI Business Intelligence Assistant\n"
    report += "=" * 50

    return report